"""Writes the regex tables of the Rust gates from the PINNED Python originals (read only; the originals never ship in the Rust companion).

  python3 scripts/gen_gate_patterns.py SRC_DIR   ->   crates/arrowbridge/src/gates/patterns_gen.rs

SRC_DIR is the pinned companion source (companion-source-export/src, commit b4db5567). Every compiled pattern of mvf_urgent and mvf_distress is copied by
its `.pattern` text and flags, so no pattern is retyped by hand; the parity vectors (gen_gate_vectors.py) then prove the Rust answers the same.
"""
import os
import re
import sys

src = os.path.abspath(sys.argv[1])
sys.path.insert(0, src)
import mvf_distress  # noqa: E402
import mvf_urgent  # noqa: E402
import mvf_fact_guard  # noqa: E402
import mvf_link_gate  # noqa: E402
import mvf_pack_safety  # noqa: E402
import mvf_tel_guard  # noqa: E402

FLAGS = ((re.I, "i"), (re.M, "m"), (re.S, "s"), (re.X, "x"))
out = ["// GENERATED by scripts/gen_gate_patterns.py from the pinned Python originals. Do not edit.\n",
       "pub struct Pat { pub name: &'static str, pub flags: &'static str, pub text: &'static str }\n\n"]


def emit(mod, name):
    r = getattr(mod, name)
    flags = "".join(c for f, c in FLAGS if r.flags & f)
    body = r.pattern
    assert '"####' not in body
    out.append('pub const %s: Pat = Pat { name: "%s", flags: "%s", text: r####"%s"#### };\n' % (name.lstrip("_").upper(), name, flags, body))


for n in ("_URGENT_EN", "_URGENT_FR", "_WALKBACK", "_OD", "_INFO", "_NEAR_PERSON", "_INTENT_BEFORE", "_INGEST", "_DROWSY", "_PET_CASE", "_PERSON_EXPOSED",
          "_TOXIC", "_PET_SWALLOWED"):
    emit(mvf_urgent, n)
for n in ("SELF_HARM_EN", "SELF_HARM_FR", "_PASSIVE"):
    emit(mvf_distress, n)
emit(mvf_tel_guard, "_TEL")
emit(mvf_fact_guard, "_FACT")
emit(mvf_link_gate, "_LINK")


def lit(x):
    return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'


# The engine crisis floor and the filtered reply (mvf_pack_safety): copied, never retyped.
floor = mvf_pack_safety.ENGINE_DEFAULT_CRISIS
assert len(floor) == 1 and set(floor[0]) == {"tel", "label_en", "label_fr"}
out.append("pub const FLOOR_TEL: &str = %s;\npub const FLOOR_LABEL_EN: &str = %s;\npub const FLOOR_LABEL_FR: &str = %s;\n" % (lit(floor[0]["tel"]), lit(floor[0]["label_en"]), lit(floor[0]["label_fr"])))
out.append("pub const FILTERED_REPLY_EN: &str = %s;\npub const FILTERED_REPLY_FR: &str = %s;\n" % (lit(mvf_pack_safety.FILTERED_REPLY["en"]), lit(mvf_pack_safety.FILTERED_REPLY["fr"])))
for n in ("URGENT_LINE", "INGEST_LINE", "ANIMAL_LINE"):
    d = getattr(mvf_urgent, n)
    out.append('pub const %s_EN: &str = %s;\npub const %s_FR: &str = %s;\n' % (n, '"' + d["en"].replace("\\", "\\\\").replace('"', '\\"') + '"', n, '"' + d["fr"].replace("\\", "\\\\").replace('"', '\\"') + '"'))
dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "crates/arrowbridge/src/gates/patterns_gen.rs")
open(dest, "w", encoding="utf-8").write("".join(out))
print("wrote", dest, len(out))
